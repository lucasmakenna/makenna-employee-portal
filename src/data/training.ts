// ─── Helper utilities ──────────────────────────────────────────────────────

/** Total number of skills across all stations. */
export function totalSkills(): number {
  return STATIONS.reduce((sum, s) => sum + s.skills.length, 0);
}

/** Number of skills completed by an employee, given their progress record. */
export function completedSkillsCount(
  progress: Record<string, { skillsCompleted: string[] }>
): number {
  return STATIONS.reduce((sum, station) => {
    const p = progress[station.id];
    return sum + (p ? p.skillsCompleted.length : 0);
  }, 0);
}

/** Look up a single station by id. Returns undefined if not found. */
export function getStation(id: string) {
  return STATIONS.find((s) => s.id === id);
}
